<?php
declare(strict_types=1);
// No DB connections, no writes. Use the real classifiers on in-memory events.
require_once __DIR__ . '/../modelo/v2/journey/JourneyV11OperationalContext.php';
date_default_timezone_set('UTC');
$ref = new ReflectionClass(JourneyPairingService::class);
$pairing = $ref->newInstanceWithoutConstructor();
$ref->getProperty('defaultToleranceSeconds')->setValue($pairing, 14400);
$policy = ['policy_id'=>6,'version'=>6,'early_entry_minutes'=>10,'repeat_minutes'=>5,'exit_priority_minutes'=>60];
$segment = static fn(string $s, string $e, int $o=1) => ['ordinal'=>$o,'scheduled_start_utc'=>$s,'scheduled_end_utc'=>$e];
$punch = static fn(int $id,string $at,?int $station=1,string $flags='[]') => ['id'=>$id,'id_personal_resuelto'=>2,'id_estacion_resuelta'=>$station,'ocurrido_at_utc'=>$at,'validation_flags'=>$flags];
$n=0;
$check = static function(bool $ok,string $label) use (&$n): void { if (!$ok) throw new RuntimeException('FAIL '.$label); echo 'PASS '.$label.PHP_EOL; $n++; };
$preview = static fn(array $s,array $p,?array $v,bool $closed=false,int $station=1) => $pairing->previewCandidatePositions($s,$p,$v,$closed,$station,2);
$night = [$segment('2026-11-26 22:00:00','2026-11-27 06:00:00')];
$day = [$segment('2026-11-27 07:00:00','2026-11-27 15:00:00')];
$p = [$punch(1,'2026-11-26 22:00:00'),$punch(2,'2026-11-27 06:05:00')];
$a=$preview($night,$p,$policy); $b=$preview($day,$p,$policy);
$check($a['primary_positions'][2]['role']==='EXIT' && !in_array(2,$b['possible_punch_ids'],true),'night exit not a too-early next entry');
$sum=JourneyV11OperationalContext::summarizePositionPreviews(['night'=>$a,'day'=>$b]);
$check($sum['possible_competition_ids']===[] && !$sum['active_revision_conflicts_checked'],'no competition observed; active revision guard not claimed');
$p = [$punch(3,'2026-11-27 07:00:00')];
$a=$preview($night,$p,$policy); $b=$preview($day,$p,$policy);
$sum=JourneyV11OperationalContext::summarizePositionPreviews(['night'=>$a,'day'=>$b]);
$check($sum['primary_collision_ids']===[3] && $sum['possible_competition_ids']===[3],'actual provisional slot collision');
$check($sum===JourneyV11OperationalContext::summarizePositionPreviews(['day'=>$b,'night'=>$a]),'deterministic summary order');
$p = [$punch(4,'2026-11-27 06:49:59'),$punch(5,'2026-11-27 06:50:00')];
$a=$preview($day,$p,$policy);
$check($a['possible_punch_ids']===[5] && $a['primary_positions'][5]['role']==='ENTRY','entry boundary');
$a=$preview($day,[$punch(6,'2026-11-27 07:00:00',2)],$policy);
$check($a['possible_punch_ids']===[] && $a['excluded'][6]==='OTHER_PHYSICAL_STATION','other physical station excluded from preview');
$a=$preview($day,[$punch(7,'2026-11-27 07:00:00',1,'["INVALID"]'),$punch(8,'2026-11-27 08:00:00',null)],$policy);
$check(count($a['invalid'])===2 && $a['primary_positions']===[],'invalid or unmapped events not assigned');
$check(JourneyV11OperationalContext::summarizePositionPreviews(['a'=>$a])['status']==='INCONCLUSIVE_POSITION_COMPETITION_OR_INVALID_EVENT','invalid preview not conclusive');
$a=$preview($day,[$punch(9,'2026-11-27 06:30:00')],null);
$check($a['algorithm']==='V1.0' && $a['primary_positions'][9]['role']==='ENTRY','actual historical classifier reused');
$p = [$punch(10,'2026-11-27 07:00:00'),$punch(11,'2026-11-27 11:30:00')];
$a=$preview($day,$p,$policy,false);$b=$preview($day,$p,$policy,true);
$check(!isset($a['primary_positions'][11]) && $b['primary_positions'][11]['role']==='EXIT','early exit depends on closure');
$split=[$segment('2026-11-27 08:00:00','2026-11-27 12:00:00',1),$segment('2026-11-27 14:00:00','2026-11-27 18:00:00',2)];
$p=[$punch(12,'2026-11-27 07:55:00'),$punch(13,'2026-11-27 12:02:00'),$punch(14,'2026-11-27 13:58:00'),$punch(15,'2026-11-27 18:05:00')];
$a=$preview($split,$p,$policy);
$check(count($a['primary_positions'])===4 && $a['primary_positions'][14]===['ordinal'=>2,'role'=>'ENTRY'],'split shift uses all segments');
$check($a===$preview(array_reverse($split),array_reverse($p),$policy),'deterministic input order');
echo "$n PASS (in-memory diagnostic only)\n";
